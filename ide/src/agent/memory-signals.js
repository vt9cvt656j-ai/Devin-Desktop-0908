// 一句用户的话值不值得**长期**记住 —— 纯判断，不碰存储。
//
// 2026-09-05 拿 1274 条真实用户消息跑旧规则：送进全局库 0 条、送进项目库 15 条，
// 而那 15 条全是测试脚本的提示词。旧规则的词表是"以后/永远/一律/记住"这一类
// 祈使语 —— 而人说偏好的时候大多不是这么说的："用中文回答""别太长""不用解释"。
// 这里把词表换成人真会说的形状，并把判据拆成三段可以分别测的：
//   ① 形状闸：太短 / 太长 / 问句 / 一次性任务 / 推迟语 → 不记；
//   ② 作用域：跨项目（说的是"我"和"回复怎么写"）还是本项目（说的是这个仓库怎么做）；
//   ③ 种类：规矩（必须/禁止/一律）还是偏好（喜欢/习惯/尽量）。
// 它**不是**主路：真实对话里明说偏好的句子很少，主路是收尾反思（模型从纠正里归纳）
// 和用户在记忆中心手写。这条只负责"用户明说了就别漏"。

/** 一次性任务的开头：这种句子不是偏好，是活。 */
const TASK_START = /^(?:帮我|请你?|去|把|将|先|再|现在|然后)?(?:修|写|做|跑|运行|编译|打包|部署|看看|读|查|测试|启动|改|加|删|实现|生成|创建|安装|检查|分析|优化|重构)/;
/** 推迟语：「下次再看」是"这件事推迟"，不是"从此每次"。 */
const DEFER = /(?:下次再|以后再|回头再|等会再|稍后再|先放着|先不管)/;

/** 跨项目的信号：说的是"我"、说的是"回复怎么写"、或者明说了"所有项目/以后都"。 */
const GLOBAL_SIGNAL = new RegExp([
  "以后(?:都|一律|每次|全部|统一)?", "永远", "每次都", "一律", "所有项目", "任何项目", "从今往后", "从现在开始",
  "都要", "都给我", "记住", "别再", "不要再", "不许再",
  "用中文", "用英文", "中文回答", "英文回答", "中文回复", "英文回复", "说中文", "讲中文", "回复用", "回答用",
  "别太长", "太长了", "简短点", "简洁点", "短一点", "直接点", "直接说", "不要解释", "不用解释", "少解释", "少废话",
  "不要客套", "不用客套", "别客气", "不要道歉", "别道歉", "不要总结", "不用总结",
  "我习惯", "我喜欢", "我不喜欢", "我讨厌", "我反感", "我一般", "我通常", "我平时",
].join("|"));
/** 本项目的信号：说的是这个仓库怎么做。 */
const PROJECT_SIGNAL = /(?:别用|不要用|不许|禁止|禁用|必须|要用|改用|统一|优先用|默认用|喜欢|讨厌|反感|风格|规范|习惯|标准是|一律|约定|命名|放在|目录)/;
/** 规矩 vs 偏好。 */
const RULE_SIGNAL = /(?:必须|禁止|不许|一律|别用|不要用|禁用|绝不|永远不|不准|只能|只许)/;

/**
 * @param {string} text 用户原话
 * @returns {{ scope: "global"|"project", kind: "rule"|"preference", text: string } | null}
 */
export function judgeDurableUtterance(text) {
  const t = String(text || "").trim().replace(/\s+/g, " ");
  // 下限 4 不是 6：「回复用中文」「用中文回答」正好 5 个字，是最常见的那种说法。
  // 这里比 _autoMemoryCapture 敢放低，因为下面还有信号词那道门，短句没有信号词照样进不来。
  if (t.length < 4 || t.length > 300) return null;
  if (/[?？]\s*$/.test(t)) return null;
  if (DEFER.test(t)) return null;
  const global = GLOBAL_SIGNAL.test(t);
  const project = PROJECT_SIGNAL.test(t);
  if (!global && !project) return null;
  // 没有跨项目信号的任务式句子（"帮我修一下，必须今天弄完"）不是持久偏好。
  if (!global && TASK_START.test(t)) return null;
  const kind = RULE_SIGNAL.test(t) ? "rule" : "preference";
  return { scope: global ? "global" : "project", kind, text: t };
}
