/**
 * 辅助调用（意图裁决这一类）该用哪个思考档位。
 *
 * ## 删掉档位 ≠ 不思考
 *
 * 意图裁决原来是把 `reasoningEffort` / `thinking*` 几个键**删掉**再发。删掉留下的是
 * **供应商默认档**，而对原生推理模型那就是深档 —— main.js 里 `_billableAiComplete`
 * 自己的注释早就写着「快通道虽然把 reasoning* 几个键都删了，模型照样推理」。
 *
 * 后果是裁决把预算全烧在推理上、正文零字节。线上两天的实测：
 *
 * · **64 次辅助调用的输出恰好卡在 4996**（= 裁决两条腿各请求的 900 + 4096 推理余量），
 *   占全部辅助调用的 13%；另有 4997 ×3、4995 ×2，是死点不是巧合；
 * · 运行中应用的能力账本里，`deepseek-v4-pro` 的裁决**工程半最近 20 条有 11 条是空的**
 *   —— 而工程半正是挂架构 / 设计那一半（语义半同期 18 ok / 2 empty）。
 *
 * 裁决半份解不出 JSON 就判 partial、**不进缓存**，同一句话下一轮重新发一遍，再烧一次。
 * 用户侧的形状就是「第一发的画像是空的 → 突然变弱智」。
 *
 * ## 为什么是封顶而不是加预算
 *
 * 加余量这条路**已经试过了**。main.js 里那段原地实测记着：
 * 「max_tokens=900 烧光、=4996 **照样烧光**，推理 0 字、正文 0 字 → 裁决永不落定」。
 * 深度推理在一次固定 schema 的分类上买不到准确率，只买到 token。
 *
 * ## 为什么不复用 `_cognitiveLegEffort`
 *
 * 那个函数在「用户没拨过档位」时返回 `{}`（不发字段）—— 而那正是这里出事的形状。
 * 它那条判据是给三条认知腿（工具编排 / 收尾评审 / 离线蒸馏）定的，有测试逐条钉着
 * （「没有档位信息 → 什么都不加，别凭空造一个默认深度出来花钱」）。那条判据的前提是
 * 「不发字段 = 便宜」，对原生推理模型不成立；但它是另一处的既有保护，不在这里动。
 */

/** 比 low 更便宜的档位：用户拨到这些就照他的来，只封上界，不往上抬。 */
const CHEAP = new Set(["off", "none", "minimal", "low"]);

/**
 * 给辅助调用算一个封顶后的思考档位。
 *
 * **永远返回一个具体值**，不返回「不发字段」—— 省略才是出事的那种形状。
 */
export function auxEffortFor(config) {
  const pref = String(config?.reasoningEffort || config?.thinkingEffort || "").toLowerCase();
  return CHEAP.has(pref) ? pref : "low";
}
