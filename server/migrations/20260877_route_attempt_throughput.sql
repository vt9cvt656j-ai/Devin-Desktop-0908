-- 出口的**吐字速度**：每秒吐多少 token。按天汇总，和 ttfb 记在同一行。
--
-- # 为什么要这一列
--
-- 派单得分原来只罚「首字延迟」（`endpoint_score` 里那个 √(ttfb/最快)）。线上实测
-- （2026-09-08，主对话 6 小时）说明那罚的是错的那一段：
--
--   一步的墙钟 = 首字 5 秒 + 输出 2000~4000 token
--   实测每步 73 秒、输出 4080 token → 约 46 token/秒
--   也就是首字只占 7%，其余 93% 是**一个字一个字吐出来**的时间。
--
-- 而吐字速度跨出口差得比首字还大（同一天、同一个模型）：
--
--   deepseek-v4-flash   3c905b00  83.2 tok/s   ·   OHub  38.4 tok/s   → 2.2 倍
--   claude-opus-5       764fe78b  52.4 tok/s   ·   「25」 37.5 tok/s   → 1.4 倍
--   grok-4.6            XXY       51.3 tok/s   ·   3ecc0e13  43.1 tok/s
--
-- 最后那行是最贵的一条：3ecc0e13 接了 787 次、XXY 只接了 79 次 —— 派单一直把流量
-- 送给慢的那个，因为它便宜一点点，而得分里根本没有「吐得快慢」这一维。
--
-- # 为什么是两个总量而不是一个平均速度
--
-- 存 Σtoken / Σ毫秒，而不是「每次算一个速度再平均」。短请求的速度噪声极大
-- （吐 50 个 token 的那次，首块抖动 200ms 就能让速度翻倍），把它和吐 4000 个 token
-- 的那次等权平均，等于让噪声主导。总量之比天然按 token 数加权，长请求说了算 ——
-- 而长请求正是用户真正在等的那些。
--
-- 口径和 ttfb 那两列一致：**只在成功且真的流出内容时累加**。失败那次的
-- 「时长」是等超时等了多久，混进去会让一条一直超时的线路显得「很慢但在服务」。
ALTER TABLE route_attempt
  -- 这一天里这个出口为这个模型吐出的 token 总数（只算完整流完的）。
  ADD COLUMN IF NOT EXISTS out_tokens_sum bigint NOT NULL DEFAULT 0,
  -- 对应的流式总毫秒：从**响应头到手**算到流结束，不含等表头那一段
  -- （那一段是 ttfb，已经单独记了；混在一起会把慢首字第二次算进速度里）。
  ADD COLUMN IF NOT EXISTS stream_ms_sum  bigint NOT NULL DEFAULT 0,
  -- 样本数。证据门槛用它，不用上面两个 —— 一次超长回答能把 token 总数顶起来，
  -- 但它仍然只是一次观测。
  ADD COLUMN IF NOT EXISTS stream_n       bigint NOT NULL DEFAULT 0;
